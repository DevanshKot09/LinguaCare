import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'summary_document.dart';

class PdfRenderer {
  static Future<Uint8List> renderSummary(SummaryDocument doc) async {
    final pdf = pw.Document();

    final fontRegular = pw.Font.helvetica();
    final fontBold = pw.Font.helveticaBold();

    if (doc.isAccessEnded) {
      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (context) => pw.Center(
            child: pw.Text(
              'Access has ended or summary is unavailable.',
              style: pw.TextStyle(font: fontBold, fontSize: 18),
            ),
          ),
        ),
      );
      return pdf.save();
    }

    if (doc.isEmptyDataset) {
      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (context) => pw.Center(
            child: pw.Text(
              'No data available for export.',
              style: pw.TextStyle(font: fontBold, fontSize: 18),
            ),
          ),
        ),
      );
      return pdf.save();
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text('LinguaCare shared summary', style: pw.TextStyle(font: fontBold, fontSize: 16)),
                pw.Text('Date: ${doc.generatedDate}', style: pw.TextStyle(font: fontRegular, fontSize: 10)),
              ],
            ),
            pw.SizedBox(height: 4),
            pw.Text('Subject: ${doc.subjectNickname} (${doc.subjectAgeBand}) | Generated by: ${doc.generatedByRole}', style: pw.TextStyle(font: fontRegular, fontSize: 11)),
            pw.Divider(),
            pw.SizedBox(height: 8),
          ],
        ),
        footer: (context) => pw.Column(
          children: [
            pw.Divider(),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text('This is a screening and practice summary. It is not a diagnosis.', style: pw.TextStyle(font: fontRegular, fontSize: 8, color: PdfColors.grey700)),
                pw.Text('Page ${context.pageNumber} of ${context.pagesCount}', style: pw.TextStyle(font: fontRegular, fontSize: 9)),
              ],
            ),
          ],
        ),
        build: (context) => [
          // Mandatory notice on page 1
          pw.Container(
            padding: const pw.EdgeInsets.all(8),
            decoration: pw.BoxDecoration(
              color: PdfColors.grey200,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4)),
            ),
            child: pw.Text(
              doc.nonDiagnosticNotice,
              style: pw.TextStyle(font: fontBold, fontSize: 11, color: PdfColors.red800),
            ),
          ),
          pw.SizedBox(height: 16),

          if (doc.isPrototype) ...[
            pw.Container(
              padding: const pw.EdgeInsets.all(6),
              decoration: pw.BoxDecoration(
                color: PdfColors.amber100,
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4)),
              ),
              child: pw.Text(
                'Prototype - not clinically validated',
                style: pw.TextStyle(font: fontBold, fontSize: 10, color: PdfColors.orange900),
              ),
            ),
            pw.SizedBox(height: 16),
          ],

          // Specialist Clinical Diagnoses & Confirmed Outcomes
          if (doc.clinicalAssessments.isNotEmpty) ...[
            pw.Text('Specialist Clinical Diagnoses & Outcomes (${doc.clinicalAssessments.length})', style: pw.TextStyle(font: fontBold, fontSize: 14)),
            pw.SizedBox(height: 8),
            ...doc.clinicalAssessments.map((a) => pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 8),
                  padding: const pw.EdgeInsets.all(10),
                  decoration: pw.BoxDecoration(
                    color: PdfColors.grey100,
                    border: pw.Border.all(color: PdfColors.grey500),
                    borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Row(
                        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                        children: [
                          pw.Text(
                            a.outcome == 'dld'
                                ? 'Confirmed Developmental Language Disorder (DLD) [ICD-11 6A01.2]'
                                : 'Clinical Outcome: ${a.outcome.toUpperCase()}',
                            style: pw.TextStyle(font: fontBold, fontSize: 11, color: a.outcome == 'dld' ? PdfColors.red900 : PdfColors.blue900),
                          ),
                          pw.Text(a.date, style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                        ],
                      ),
                      pw.SizedBox(height: 4),
                      pw.Text('Severity: ${a.severity.toUpperCase()}', style: pw.TextStyle(font: fontBold, fontSize: 10)),
                      if (a.domainsAffected.isNotEmpty) ...[
                        pw.SizedBox(height: 3),
                        pw.Text('Domains Affected: ${a.domainsAffected.join(", ")}', style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                      ],
                      if (a.note != null && a.note!.isNotEmpty) ...[
                        pw.SizedBox(height: 4),
                        pw.Text('Clinical Notes: ${a.note}', style: pw.TextStyle(font: fontRegular, fontSize: 10, color: PdfColors.grey800)),
                      ],
                    ],
                  ),
                )),
            pw.SizedBox(height: 16),
          ],

          // Screening Results
          if (doc.screeningResults.isNotEmpty) ...[
            pw.Text('Screening Results (${doc.screeningResults.length})', style: pw.TextStyle(font: fontBold, fontSize: 14)),
            pw.SizedBox(height: 8),
            ...doc.screeningResults.map((s) => pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 8),
                  padding: const pw.EdgeInsets.all(8),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey400),
                    borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4)),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Row(
                        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                        children: [
                          pw.Text('Risk: ${s.riskWording}', style: pw.TextStyle(font: fontBold, fontSize: 12)),
                          pw.Text(s.date, style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                        ],
                      ),
                      pw.SizedBox(height: 4),
                      pw.Text('Confidence: ${s.confidence} | Version: ${s.instrumentVersion}', style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                      if (s.domainLevels.isNotEmpty) ...[
                        pw.SizedBox(height: 4),
                        pw.Text('Domains: ${s.domainLevels.join(", ")}', style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                      ],
                      if (s.urgentNoticeTriggered) ...[
                        pw.SizedBox(height: 4),
                        pw.Text('Urgent professional check recommended.', style: pw.TextStyle(font: fontBold, fontSize: 10, color: PdfColors.red700)),
                      ],
                    ],
                  ),
                )),
            pw.SizedBox(height: 16),
          ],

          // Practice Summary
          if (doc.practiceSummary.isNotEmpty) ...[
            pw.Text('Practice Summary (${doc.practiceSummary.length})', style: pw.TextStyle(font: fontBold, fontSize: 14)),
            pw.SizedBox(height: 8),
            ...doc.practiceSummary.map((p) => pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 6),
                  padding: const pw.EdgeInsets.all(6),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey300),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text('Domain: ${p.domain} (${p.date})', style: pw.TextStyle(font: fontBold, fontSize: 11)),
                      pw.SizedBox(height: 2),
                      pw.Text(p.summaryText, style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                      pw.SizedBox(height: 2),
                      pw.Text('Duration: ${p.durationMinutes} mins | Support: ${p.supportLevel}', style: pw.TextStyle(font: fontRegular, fontSize: 9, color: PdfColors.grey700)),
                    ],
                  ),
                )),
            pw.SizedBox(height: 16),
          ],

          // Goals
          if (doc.goals.isNotEmpty) ...[
            pw.Text('Goals (${doc.goals.length})', style: pw.TextStyle(font: fontBold, fontSize: 14)),
            pw.SizedBox(height: 8),
            ...doc.goals.map((g) => pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 6),
                  padding: const pw.EdgeInsets.all(6),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey300),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(g.description, style: pw.TextStyle(font: fontBold, fontSize: 11)),
                      pw.SizedBox(height: 2),
                      pw.Text('Domain: ${g.domain} | Status: ${g.status} | Progress: ${g.progress}%', style: pw.TextStyle(font: fontRegular, fontSize: 10)),
                    ],
                  ),
                )),
            pw.SizedBox(height: 16),
          ],

          // Observations
          if (doc.observations.isNotEmpty) ...[
            pw.Text('Observations (${doc.observations.length})', style: pw.TextStyle(font: fontBold, fontSize: 14)),
            pw.SizedBox(height: 8),
            ...doc.observations.map((o) => pw.Container(
                  margin: const pw.EdgeInsets.only(bottom: 6),
                  padding: const pw.EdgeInsets.all(6),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey300),
                  ),
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(o.note, style: pw.TextStyle(font: fontRegular, fontSize: 11)),
                      pw.SizedBox(height: 2),
                      pw.Text('Setting: ${o.setting} | Date: ${o.date}', style: pw.TextStyle(font: fontRegular, fontSize: 9, color: PdfColors.grey700)),
                    ],
                  ),
                )),
          ],
        ],
      ),
    );

    return pdf.save();
  }
}
